#!/usr/bin/env node
/**
 * The one source of the neutral scheme colours: `src/foundations/scheme-colors.json` (hex).
 * This script writes every copy the app needs and nothing else may hold these colours:
 *
 *  - `src/foundations/scheme-colors.generated.css`: the `--scheme-*` / `--media-*` tokens as
 *    literal `oklch()` (hue spelled out; Chrome turns near-neutral hex into `hue: none`,
 *    which paints derived washes red-brown, so the browser never converts these itself);
 *  - `src/lib/scheme-colors.generated.ts`: the hex values for TypeScript;
 *  - the first-paint block of `index.html` and the theme-color of `public/assets/theme-boot.js`
 *    (marked `scheme-colors:begin` / `scheme-colors:end`).
 *
 * `node scripts/sync-scheme-colors.mjs` writes; `--check` exits 1 when a copy is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const path = (p) => resolve(root, p);

/** sRGB hex to `oklch(L C H)` with the hue always written out. */
export function hexToOklch(hex) {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const chroma = Math.hypot(a, bb);
  const hue = chroma < 1e-4 ? 0 : ((Math.atan2(bb, a) * 180) / Math.PI + 360) % 360;
  const n = (v, d) => String(Number(v.toFixed(d)));
  return `oklch(${n(L, 4)} ${n(chroma, 4)} ${n(hue, 2)})`;
}

const colors = JSON.parse(readFileSync(path("src/foundations/scheme-colors.json"), "utf8"));

const SCHEME_TOKENS = [
  ["surface", "--scheme-surface"],
  ["sidebarSurface", "--scheme-sidebar-surface"],
  ["ink", "--scheme-ink"],
  ["onInk", "--scheme-on-ink"],
  ["letter", "--scheme-letter"],
];

function declarations(scheme, tokens, indent = "  ") {
  return tokens
    .map(([key, name]) => `${indent}${name}: ${hexToOklch(scheme[key])}; /* ${scheme[key]} */`)
    .join("\n");
}

export function renderCss() {
  return `/* Generated by scripts/sync-scheme-colors.mjs from scheme-colors.json. Do not edit. */

/* Light paper, plus the media surface (one dark paper in both themes). */
:where(:root, :root *) {
${declarations(colors.light, SCHEME_TOKENS)}
${declarations(colors.media, [
  ["surface", "--media-surface"],
  ["ink", "--media-ink"],
])}
}

/* Dark paper. Declared after light: both are zero-specificity, so order decides. */
:where(:root[data-theme="dark"], :root[data-theme="dark"] *) {
${declarations(colors.dark, SCHEME_TOKENS)}
}
`;
}

export function renderTs() {
  return `// Generated by scripts/sync-scheme-colors.mjs from src/foundations/scheme-colors.json. Do not edit.
export const SCHEME_COLORS = ${JSON.stringify(colors, null, 2)} as const;
`;
}

const HTML_BEGIN = "<!-- scheme-colors:begin -->";
const HTML_END = "<!-- scheme-colors:end -->";
const JS_BEGIN = "/* scheme-colors:begin */";
const JS_END = "/* scheme-colors:end */";

function between(source, begin, end, body, file) {
  const from = source.indexOf(begin);
  const to = source.indexOf(end);
  if (from < 0 || to < from) throw new Error(`${file}: missing ${begin} … ${end} markers`);
  return source.slice(0, from + begin.length) + body + source.slice(to);
}

export function renderIndexHtml(source) {
  const body = `
    <style>
      html,
      body {
        background-color: ${colors.light.sidebarSurface};
      }
      html[data-theme="dark"],
      html[data-theme="dark"] body {
        background-color: ${colors.dark.surface};
      }
    </style>
    `;
  const withBlock = between(source, HTML_BEGIN, HTML_END, body, "index.html");
  return withBlock.replace(
    /<meta name="theme-color" content="#[0-9a-f]{6}" \/>/i,
    `<meta name="theme-color" content="${colors.light.sidebarSurface}" />`,
  );
}

export function renderThemeBoot(source) {
  const body = `
  var WGW_THEME_COLOR = { light: "${colors.light.sidebarSurface}", dark: "${colors.dark.sidebarSurface}" };
  `;
  const withBlock = between(source, JS_BEGIN, JS_END, body, "theme-boot.js");
  return withBlock;
}

const outputs = () => [
  ["src/foundations/scheme-colors.generated.css", () => renderCss()],
  ["src/lib/scheme-colors.generated.ts", () => renderTs()],
  ["index.html", (s) => renderIndexHtml(s)],
  ["public/assets/theme-boot.js", (s) => renderThemeBoot(s)],
];

export function syncSchemeColors({ check }) {
  const stale = [];
  for (const [file, render] of outputs()) {
    let current = "";
    try {
      current = readFileSync(path(file), "utf8");
    } catch {}
    const next = render(current);
    if (next === current) continue;
    stale.push(file);
    if (!check) writeFileSync(path(file), next);
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = syncSchemeColors({ check });
  if (check && stale.length) {
    console.error(`Scheme colours out of date: ${stale.join(", ")}. Run: pnpm sync:scheme-colors`);
    process.exit(1);
  }
  if (!check && stale.length) console.log(`Updated ${stale.join(", ")}`);
}
